    const double fp2_0 = -(1.0*b0*fp2_bdot)-1.0*C1_0; 
    const double fp2_1 = -(1.0*b1*fp2_bdot)-1.0*C1_1; 
    const double fp2_2 = -(1.0*b2*fp2_bdot)-1.0*C1_2; 
    const double xil_0 = gl0*xi; 
    const double xil_1 = gl1*xi; 
    const double xil_2 = 0.0; 
    const double xibl = b2*xil_2+b1*xil_1+b0*xil_0; 
    const double plg_bdot = b2*xil_2+b1*xil_1+b0*xil_0+b1*gx1+b0*gx0; 
    const double plg_0 = xil_0-1.0*b0*plg_bdot+gx0; 
    const double plg_1 = xil_1-1.0*b1*plg_bdot+gx1; 
    const double plg_2 = xil_2-1.0*b2*plg_bdot; 
    const double pl3g_bdot = b2*xil_2+b1*xil_1+b0*xil_0+3.0*b1*gx1+3.0*b0*gx0; 
    const double pl3g_0 = xil_0-1.0*b0*pl3g_bdot+3.0*gx0; 
    const double pl3g_1 = xil_1-1.0*b1*pl3g_bdot+3.0*gx1; 
    const double pl3g_2 = xil_2-1.0*b2*pl3g_bdot; 
    const double bbeta_0 = b0*beta; 
    const double bbeta_1 = b1*beta; 
    const double bbeta_2 = b2*beta; 
    const double PU0_bdot = b2*gu0_2+b1*gu0_1+b0*gu0_0; 
    const double PU0_0 = gu0_0-1.0*PU0_bdot*b0; 
    const double PU0_1 = gu0_1-1.0*PU0_bdot*b1; 
    const double PU0_2 = gu0_2-1.0*PU0_bdot*b2; 
