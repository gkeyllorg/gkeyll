    cv[460 + n] = 6.0*R2_2*th; 
    cv[465 + n] = -(6.0*R2_2*pow(th,2)); 
    cv[470 + n] = -(1.0*xil_2); 
    cv[475 + n] = -(1.0*plg_2)-1.0*bbeta_2; 
    cv[480 + n] = -(4.0*pl3g_2*th)-4.0*bbeta_2*th; 
    cv[485 + n] = 2.0*pl3g_2*pow(th,2)+2.0*bbeta_2*pow(th,2); 
    cv[490 + n] = fp1_2; 
