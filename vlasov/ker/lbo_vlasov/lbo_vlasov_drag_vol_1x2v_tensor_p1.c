  f0[1] = 0.7071067811865475*f[3]-0.7071067811865475*f[5]; 
  f0[2] = 0.7071067811865475*f[8]-0.7071067811865475*f[12]; 
  f0[3] = 0.7071067811865475*f[2]-0.7071067811865475*f[4]; 
  f0[4] = 0.7071067811865475*f[6]-0.7071067811865475*f[9]; 
  f0[5] = 0.7071067811865475*f[13]-0.7071067811865475*f[15]; 
  f0[6] = 0.7071067811865475*f[7]-0.7071067811865475*f[10]; 
  f0[7] = 0.7071067811865475*f[11]-0.7071067811865475*f[14]; 
  f0[8] = 0.7071067811865475*f[16]-0.7071067811865475*f[17]; 
  double G0[9]; 
  G0[1] = f0[1]*b0_vy+1.7320508075688772*f0[0]*a0_vy; 
  G0[2] = 2.0*f0[2]*b0_vy+2.23606797749979*f0[0]*b0_vy+3.872983346207417*f0[1]*a0_vy; 
  G0[3] = f0[3]*b0_vx+1.7320508075688772*f0[0]*a0_vx; 
  G0[4] = f0[4]*b0_vy+f0[4]*b0_vx+1.7320508075688772*f0[3]*a0_vy+1.7320508075688772*f0[1]*a0_vx; 
  G0[5] = 2.0*f0[5]*b0_vy+2.23606797749979*f0[3]*b0_vy+f0[5]*b0_vx+3.872983346207417*f0[4]*a0_vy+1.7320508075688772*f0[2]*a0_vx; 
  G0[6] = 2.0*f0[6]*b0_vx+2.23606797749979*f0[0]*b0_vx+3.872983346207417*f0[3]*a0_vx; 
  G0[7] = f0[7]*b0_vy+2.0*f0[7]*b0_vx+2.23606797749979*f0[1]*b0_vx+1.7320508075688772*f0[6]*a0_vy+3.872983346207417*f0[4]*a0_vx; 
  G0[8] = 2.0*f0[8]*b0_vy+2.23606797749979*f0[6]*b0_vy+2.0*f0[8]*b0_vx+2.23606797749979*f0[2]*b0_vx+3.872983346207417*f0[7]*a0_vy+3.872983346207417*f0[5]*a0_vx; 
  const double nuq1 = 0.7071067811865475*nuSum[1]+0.7071067811865475*nuSum[0]; 
